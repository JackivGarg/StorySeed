"""Write small, inspectable reports without saving large model artifacts."""

import json
from pathlib import Path


PROJECT_ROOT = Path(__file__).resolve().parents[2]


def record(name: str, results: dict) -> None:
    directory = PROJECT_ROOT / "reports" / "phase01"
    directory.mkdir(parents=True, exist_ok=True)
    serialized = json.dumps(results, indent=2, ensure_ascii=False)
    (directory / f"{name}.json").write_text(serialized + "\n", encoding="utf-8")
    text = f"# Observed Phase 1 example: {name}\n\n"
    text += "Generated by the recorded lesson command. Values below are actual execution results.\n\n"
    text += f"```json\n{serialized}\n```\n"
    (directory / f"{name}.md").write_text(text, encoding="utf-8")
    print(serialized)
