"""A bounded, revision-pinned TinyStories teaching corpus, not the main run."""

import hashlib
import json
from pathlib import Path
import statistics
import urllib.request

ROOT = Path(__file__).resolve().parents[2]
RAW = ROOT / 'data/raw/phase02'
PROCESSED = ROOT / 'data/processed/phase02'
MANIFESTS = ROOT / 'data/manifests/phase02'
REPORTS = ROOT / 'reports/phase02'
REVISION = 'f54c09fd23315a6f9c86f9dc80f725de7d8f9c64'
DATASET = 'roneneldan/TinyStories'
SOURCE_FILE = 'TinyStories-train.txt'
PREFIX_BYTES = 1_048_576
DELIMITER = b'<|endoftext|>'


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def write_json(path: Path, value) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')


def read_jsonl(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text(encoding='utf-8').splitlines() if line]


def write_jsonl(path: Path, rows) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open('w', encoding='utf-8', newline='\n') as stream:
        for row in rows:
            stream.write(json.dumps(row, ensure_ascii=False) + '\n')


def record(name: str, result: dict) -> None:
    write_json(REPORTS / (name + '.json'), result)
    (REPORTS / (name + '.md')).write_text(
        '# Observed Phase 2 result: ' + name + '\n\n'
        'Generated by the recorded command. Student understanding remains unmeasured.\n\n'
        '```json\n' + json.dumps(result, indent=2, ensure_ascii=False) + '\n```\n', encoding='utf-8')
    print(json.dumps(result, indent=2, ensure_ascii=False))


def capture_prefix() -> dict:
    """Read at most 1 MiB even when the server ignores Range; discard the tail."""
    url = f'https://huggingface.co/datasets/{DATASET}/resolve/{REVISION}/{SOURCE_FILE}'
    request = urllib.request.Request(url, headers={
        'Range': f'bytes=0-{PREFIX_BYTES - 1}', 'User-Agent': 'StorySeed-teaching/0.2'})
    with urllib.request.urlopen(request, timeout=20) as response:
        prefix = response.read(PREFIX_BYTES)
        status = response.status
        content_range = response.headers.get('Content-Range')
    if status not in (200, 206):
        raise ValueError(f'Unexpected source HTTP status {status}')
    if status == 206 and (not content_range or not content_range.startswith('bytes 0-')):
        raise ValueError('The source did not return a prefix starting at byte zero.')
    segments = prefix.split(DELIMITER)
    if len(segments) < 20:
        raise ValueError('Not enough complete delimited stories in the source prefix.')
    rows = []
    empty = 0
    for index, segment in enumerate(segments[:-1]):
        text = segment.decode('utf-8-sig').replace('\r\n', '\n').strip()
        if not text:
            empty += 1
            continue
        rows.append({'source_index': index, 'text': text, 'sha256': sha256(text.encode('utf-8'))})
    RAW.mkdir(parents=True, exist_ok=True)
    (RAW / 'source-prefix.bin').write_bytes(prefix)
    write_jsonl(RAW / 'stories.jsonl', rows)
    card_url = f'https://huggingface.co/datasets/{DATASET}/raw/{REVISION}/README.md'
    with urllib.request.urlopen(card_url, timeout=20) as response:
        card = response.read(100_000).decode('utf-8')
    if 'license: cdla-sharing-1.0' not in card:
        raise ValueError('Pinned dataset-card license metadata differs; inspect before proceeding.')
    (RAW / 'UPSTREAM_README.md').write_text(card, encoding='utf-8')
    sizes = [len(row['text'].encode('utf-8')) for row in rows]
    manifest = {
        'dataset': DATASET, 'revision': REVISION, 'source_file': SOURCE_FILE,
        'source_url': url, 'dataset_card_url': card_url, 'license_declared_by_card': 'cdla-sharing-1.0',
        'authors': ['Ronen Eldan', 'Yuanzhi Li'], 'paper': 'https://arxiv.org/abs/2305.07759',
        'retrieved_client_date': '2026-10-16', 'client_timezone': 'Asia/Calcutta', 'sampling': 'first bounded source bytes; convenience pilot, not a random or representative sample',
        'prefix_bytes': len(prefix), 'prefix_sha256': sha256(prefix), 'http_status': status,
        'content_range': content_range, 'complete_stories': len(rows), 'empty_segments_dropped': empty,
        'incomplete_tail_bytes_discarded': len(segments[-1]),
        'cleaning': 'strict UTF-8, CRLF to LF, strip outer whitespace; no spelling/case repair',
        'raw_jsonl_sha256': sha256((RAW / 'stories.jsonl').read_bytes()),
        'card_sha256': sha256(card.encode('utf-8')),
        'story_bytes': {'min': min(sizes), 'median': statistics.median(sizes), 'max': max(sizes)},
        'purpose': 'Phase 2 pipeline teaching; not the eventual main-training corpus',
        'command': '.venv/Scripts/python scripts/phase02/01_capture_corpus.py',
        'redistribution': 'raw stories stay ignored locally; retain upstream attribution and review declared terms before sharing data',
    }
    write_json(MANIFESTS / 'source.json', manifest)
    record('01_corpus', manifest)
    return manifest
